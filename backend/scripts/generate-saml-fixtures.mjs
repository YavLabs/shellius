/**
 * generate-saml-fixtures.mjs — build the committed SAML test corpus.
 *
 *   node backend/scripts/generate-saml-fixtures.mjs
 *
 * Writes `src/services/__tests__/fixtures/saml/`: a THROWAWAY RSA key pair
 * (two of them — the "IdP" and an unrelated "attacker"), and a set of signed
 * SAML responses, one per thing that must be refused.
 *
 * The fixtures are committed so the tests run against fixed bytes rather than
 * bytes the test itself just produced. A test that signs its own input can
 * only ever prove the verifier agrees with the signer; a fixed corpus can
 * prove the verifier refuses a document neither it nor the test can adjust.
 *
 * NOTHING HERE IS A REAL KEY. The private keys in the fixture directory are
 * generated by this script, used only by the test suite, and have never
 * protected anything. Re-run the script to replace them at any time.
 *
 * All timestamps are fixed (2026-01-01). The tests pin `Date` with jest fake
 * timers rather than regenerating, so a fixture that passes today passes in
 * five years.
 */

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
import { SignedXml } from 'xml-crypto';
import sshpk from 'sshpk';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'src', 'services', '__tests__', 'fixtures', 'saml');

// --- fixed values the tests assert against ---------------------------------
export const SP_ENTITY_ID = 'https://shellius.test/api/auth/sso/saml/metadata/prov_aaa';
export const ACS_URL = 'https://shellius.test/api/auth/sso/saml/acs/prov_aaa';
export const OTHER_ACS_URL = 'https://shellius.test/api/auth/sso/saml/acs/prov_bbb';
export const IDP_ENTITY_ID = 'https://idp.test/entity';
export const OTHER_IDP_ENTITY_ID = 'https://evil-idp.test/entity';
export const REQUEST_ID = '_00000000000000000000000000000000000000000a';
export const ISSUE_INSTANT = '2026-01-01T00:00:00Z';
export const NOT_BEFORE = '2026-01-01T00:00:00Z';
export const NOT_ON_OR_AFTER = '2026-01-01T00:05:00Z';
export const ASSERTION_ID = '_assertion0000000000000000000000000000001';
export const RESPONSE_ID = '_response00000000000000000000000000000001';
export const NAME_ID = 'alice@example.com';

const SIG_SHA256 = 'http://www.w3.org/2001/04/xmldsig-more#rsa-sha256';
const SIG_SHA1 = 'http://www.w3.org/2000/09/xmldsig#rsa-sha1';
const DIG_SHA256 = 'http://www.w3.org/2001/04/xmlenc#sha256';
const DIG_SHA1 = 'http://www.w3.org/2000/09/xmldsig#sha1';
const C14N = 'http://www.w3.org/2001/10/xml-exc-c14n#';
const ENVELOPED = 'http://www.w3.org/2000/09/xmldsig#enveloped-signature';

function makeKeyPair(cn) {
  const { privateKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 2048,
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    publicKeyEncoding: { type: 'spki', format: 'pem' },
  });
  const parsed = sshpk.parsePrivateKey(privateKey, 'pem');
  const cert = sshpk.createSelfSignedCertificate(sshpk.identityFromDN(`CN=${cn}`), parsed, {
    lifetime: 100 * 365 * 24 * 60 * 60, // fixtures must not rot
    purposes: ['signature'],
  });
  return { privateKey, certificate: cert.toBuffer('pem').toString('ascii') };
}

/**
 * Build a SAML Response. Every knob here exists because some test needs to
 * turn exactly one thing wrong and leave the rest correct.
 */
function responseXml({
  audience = SP_ENTITY_ID,
  destination = ACS_URL,
  recipient = ACS_URL,
  inResponseTo = REQUEST_ID,
  issuer = IDP_ENTITY_ID,
  notBefore = NOT_BEFORE,
  notOnOrAfter = NOT_ON_OR_AFTER,
  issueInstant = ISSUE_INSTANT,
  assertionId = ASSERTION_ID,
  responseId = RESPONSE_ID,
  nameId = NAME_ID,
  nameIdFormat = 'urn:oasis:names:tc:SAML:1.1:nameid-format:emailAddress',
  attributes = [
    { name: 'http://schemas.xmlsoap.org/ws/2005/05/identity/claims/emailaddress', values: ['alice@example.com'] },
    { name: 'displayName', values: ['Alice Example'] },
    { name: 'groups', values: ['Engineering', 'Oncall'] },
  ],
  doctype = '',
  omitConditions = false,
  omitNameId = false,
  extraResponseAttrs = '',
} = {}) {
  const attrXml = attributes
    .map(
      (a) =>
        `      <saml:Attribute Name="${a.name}"${a.friendlyName ? ` FriendlyName="${a.friendlyName}"` : ''} NameFormat="urn:oasis:names:tc:SAML:2.0:attrname-format:unspecified">\n` +
        a.values.map((v) => `        <saml:AttributeValue>${v}</saml:AttributeValue>`).join('\n') +
        `\n      </saml:Attribute>`
    )
    .join('\n');

  const conditions = omitConditions
    ? ''
    : `    <saml:Conditions NotBefore="${notBefore}" NotOnOrAfter="${notOnOrAfter}">
      <saml:AudienceRestriction>
        <saml:Audience>${audience}</saml:Audience>
      </saml:AudienceRestriction>
    </saml:Conditions>
`;

  const subject = omitNameId
    ? `    <saml:Subject>
      <saml:SubjectConfirmation Method="urn:oasis:names:tc:SAML:2.0:cm:bearer">
        <saml:SubjectConfirmationData${inResponseTo ? ` InResponseTo="${inResponseTo}"` : ''}${recipient ? ` Recipient="${recipient}"` : ''} NotOnOrAfter="${notOnOrAfter}"/>
      </saml:SubjectConfirmation>
    </saml:Subject>
`
    : `    <saml:Subject>
      <saml:NameID Format="${nameIdFormat}">${nameId}</saml:NameID>
      <saml:SubjectConfirmation Method="urn:oasis:names:tc:SAML:2.0:cm:bearer">
        <saml:SubjectConfirmationData${inResponseTo ? ` InResponseTo="${inResponseTo}"` : ''}${recipient ? ` Recipient="${recipient}"` : ''} NotOnOrAfter="${notOnOrAfter}"/>
      </saml:SubjectConfirmation>
    </saml:Subject>
`;

  return `<?xml version="1.0" encoding="UTF-8"?>${doctype}
<samlp:Response xmlns:samlp="urn:oasis:names:tc:SAML:2.0:protocol" xmlns:saml="urn:oasis:names:tc:SAML:2.0:assertion" ID="${responseId}" Version="2.0" IssueInstant="${issueInstant}"${destination ? ` Destination="${destination}"` : ''}${inResponseTo ? ` InResponseTo="${inResponseTo}"` : ''}${extraResponseAttrs}>
  <saml:Issuer>${issuer}</saml:Issuer>
  <samlp:Status><samlp:StatusCode Value="urn:oasis:names:tc:SAML:2.0:status:Success"/></samlp:Status>
  <saml:Assertion xmlns:saml="urn:oasis:names:tc:SAML:2.0:assertion" ID="${assertionId}" Version="2.0" IssueInstant="${issueInstant}">
    <saml:Issuer>${issuer}</saml:Issuer>
${subject}${conditions}    <saml:AuthnStatement AuthnInstant="${issueInstant}" SessionIndex="_session0001">
      <saml:AuthnContext>
        <saml:AuthnContextClassRef>urn:oasis:names:tc:SAML:2.0:ac:classes:PasswordProtectedTransport</saml:AuthnContextClassRef>
      </saml:AuthnContext>
    </saml:AuthnStatement>
    <saml:AttributeStatement>
${attrXml}
    </saml:AttributeStatement>
  </saml:Assertion>
</samlp:Response>`;
}

/** Sign one element (Assertion or Response) in place, enveloped. */
function sign(xml, { privateKey, certificate, target = 'Assertion', sigAlg = SIG_SHA256, digestAlg = DIG_SHA256 }) {
  const sig = new SignedXml({ privateKey, publicCert: certificate });
  sig.signatureAlgorithm = sigAlg;
  sig.canonicalizationAlgorithm = C14N;
  sig.addReference({
    xpath: `//*[local-name(.)='${target}']`,
    transforms: [ENVELOPED, C14N],
    digestAlgorithm: digestAlg,
  });
  sig.computeSignature(xml, {
    location: { reference: `//*[local-name(.)='${target}']/*[local-name(.)='Issuer']`, action: 'after' },
  });
  return sig.getSignedXml();
}

const write = (name, xml) => {
  fs.writeFileSync(path.join(OUT, name), xml.endsWith('\n') ? xml : `${xml}\n`);
  return xml;
};

function main() {
  fs.mkdirSync(OUT, { recursive: true });

  const idp = makeKeyPair('shellius-test-idp');
  const attacker = makeKeyPair('shellius-test-attacker');

  fs.writeFileSync(path.join(OUT, 'idp-key.pem'), idp.privateKey);
  fs.writeFileSync(path.join(OUT, 'idp-cert.pem'), idp.certificate);
  fs.writeFileSync(path.join(OUT, 'attacker-key.pem'), attacker.privateKey);
  fs.writeFileSync(path.join(OUT, 'attacker-cert.pem'), attacker.certificate);
  fs.writeFileSync(
    path.join(OUT, 'constants.json'),
    `${JSON.stringify(
      {
        SP_ENTITY_ID,
        ACS_URL,
        OTHER_ACS_URL,
        IDP_ENTITY_ID,
        OTHER_IDP_ENTITY_ID,
        REQUEST_ID,
        ISSUE_INSTANT,
        NOT_BEFORE,
        NOT_ON_OR_AFTER,
        ASSERTION_ID,
        RESPONSE_ID,
        NAME_ID,
        NOW: '2026-01-01T00:01:00Z',
      },
      null,
      2
    )}\n`
  );

  const withIdp = (xml, opts = {}) => sign(xml, { ...idp, ...opts });

  // 1. The known-good document every other fixture is a single mutation of.
  write('valid.xml', withIdp(responseXml()));

  // 2. No signature anywhere. The single most important refusal.
  write('unsigned.xml', responseXml());

  // 3. Signed by a key we do not trust. Structurally perfect.
  write('wrong-key.xml', sign(responseXml(), { ...attacker }));

  // 4. Valid signature, then one character of the NameID changed afterwards.
  {
    const signed = withIdp(responseXml());
    write('tampered-nameid.xml', signed.replace('alice@example.com<', 'admin@example.com<'));
  }

  // 5. Signature over the RESPONSE only; the assertion inside it is unsigned.
  //    The classic "it was signed, wasn't it?" bypass.
  write('response-signed-assertion-unsigned.xml', withIdp(responseXml(), { target: 'Response' }));

  // 6. Signature wrapping: a legitimately signed assertion is kept (so its
  //    signature still verifies against its own ID) and a forged assertion
  //    with a DIFFERENT id is added as a sibling, hoping the verifier reads
  //    one and trusts the other.
  {
    const legit = withIdp(responseXml());
    const forged = responseXml({ assertionId: '_forged0000000000000000000000000000000001', nameId: 'admin@example.com' })
      .split('<saml:Assertion')[1]
      .split('</saml:Assertion>')[0];
    write(
      'signature-wrapping.xml',
      legit.replace('</samlp:Response>', `<saml:Assertion${forged}</saml:Assertion></samlp:Response>`)
    );
  }

  // 7. Signature wrapping, inner variant: the forged assertion is the one at
  //    the top level and the signed original is buried inside an Extensions
  //    element where a naive xpath still finds its signature.
  {
    const legit = withIdp(responseXml());
    const signedAssertion = `<saml:Assertion${legit.split('<saml:Assertion')[1].split('</saml:Assertion>')[0]}</saml:Assertion>`;
    const forged = responseXml({ nameId: 'admin@example.com' });
    write(
      'signature-wrapping-nested.xml',
      forged.replace(
        '<samlp:Status>',
        `<samlp:Extensions>${signedAssertion}</samlp:Extensions><samlp:Status>`
      )
    );
  }

  // 8. The "SAML raw XML comment" bug (CVE-2017-11428 and friends): a comment
  //    splits the NameID text node. A verifier that reads only the first text
  //    node sees "alice@example.com" while the signature covers
  //    "alice@example.com.evil.example.org".
  write(
    'comment-truncation.xml',
    withIdp(responseXml({ nameId: 'alice@example.com<!---->.evil.example.org' }))
  );

  // 9-12. One field wrong each, everything else correct and signed.
  write('wrong-audience.xml', withIdp(responseXml({ audience: 'https://someone-else.test/sp' })));
  write('wrong-destination.xml', withIdp(responseXml({ destination: OTHER_ACS_URL })));
  write('wrong-recipient.xml', withIdp(responseXml({ recipient: OTHER_ACS_URL })));
  write('wrong-issuer.xml', withIdp(responseXml({ issuer: OTHER_IDP_ENTITY_ID })));

  // 13-14. Time.
  write(
    'expired.xml',
    withIdp(responseXml({ notBefore: '2025-12-31T23:00:00Z', notOnOrAfter: '2025-12-31T23:05:00Z', issueInstant: '2025-12-31T23:00:00Z' }))
  );
  write(
    'not-yet-valid.xml',
    withIdp(responseXml({ notBefore: '2026-01-01T02:00:00Z', notOnOrAfter: '2026-01-01T02:05:00Z' }))
  );
  // Inside NotBefore only once a 60s skew is allowed.
  write(
    'skew-30s.xml',
    withIdp(responseXml({ notBefore: '2026-01-01T00:01:30Z', notOnOrAfter: '2026-01-01T00:06:30Z' }))
  );

  // 15. No AudienceRestriction at all.
  write('no-conditions.xml', withIdp(responseXml({ omitConditions: true })));

  // 16. No NameID — nothing stable to key an identity on.
  write('no-nameid.xml', withIdp(responseXml({ omitNameId: true })));

  // 17. Transient NameID — unique per session, useless as a subject.
  write(
    'transient-nameid.xml',
    withIdp(
      responseXml({
        nameIdFormat: 'urn:oasis:names:tc:SAML:2.0:nameid-format:transient',
        nameId: '_transient00000000000000000001',
      })
    )
  );

  // 18. Persistent NameID with a separate email attribute — the shape Entra
  //     and Okta actually produce when configured for a persistent id.
  write(
    'persistent-nameid.xml',
    withIdp(
      responseXml({
        nameIdFormat: 'urn:oasis:names:tc:SAML:2.0:nameid-format:persistent',
        nameId: 'f1e2d3c4-0000-0000-0000-abcdefabcdef',
        attributes: [
          { name: 'http://schemas.xmlsoap.org/ws/2005/05/identity/claims/emailaddress', values: ['alice@example.com'] },
          { name: 'http://schemas.microsoft.com/identity/claims/displayname', values: ['Alice Example'] },
          { name: 'http://schemas.microsoft.com/identity/claims/objectidentifier', values: ['aad-object-id-1'] },
        ],
      })
    )
  );

  // 19. Shibboleth shape: OID attribute Names with human FriendlyNames.
  write(
    'friendly-name-attributes.xml',
    withIdp(
      responseXml({
        attributes: [
          { name: 'urn:oid:0.9.2342.19200300.100.1.3', friendlyName: 'mail', values: ['alice@example.com'] },
          { name: 'urn:oid:2.16.840.1.113730.3.1.241', friendlyName: 'displayName', values: ['Alice Example'] },
        ],
      })
    )
  );

  // 20. SHA-1 signature and digest. Structurally valid, cryptographically old.
  write('sha1-signed.xml', withIdp(responseXml(), { sigAlg: SIG_SHA1, digestAlg: DIG_SHA1 }));

  // 21. DTD present. Signed, so only the DOCTYPE refusal can stop it.
  write(
    'doctype.xml',
    withIdp(
      responseXml({
        doctype: '\n<!DOCTYPE samlp:Response [<!ENTITY xxe SYSTEM "file:///etc/passwd">]>',
      })
    )
  );

  // 22. Unsolicited: no InResponseTo anywhere. This is what an IdP-initiated
  //     sign-in legitimately looks like, and what a replay of a stolen
  //     assertion looks like when the thief strips the binding.
  write('no-inresponseto.xml', withIdp(responseXml({ inResponseTo: null })));

  // 23. Bound to a DIFFERENT AuthnRequest than the one we are tracking.
  write('other-inresponseto.xml', withIdp(responseXml({ inResponseTo: '_00000000000000000000000000000000000000ff' })));

  // 24. Two assertions in one response.
  {
    const legit = withIdp(responseXml());
    const second = `<saml:Assertion${responseXml({ assertionId: '_second000000000000000000000000000000001' }).split('<saml:Assertion')[1].split('</saml:Assertion>')[0]}</saml:Assertion>`;
    write('two-assertions.xml', legit.replace('</samlp:Response>', `${second}</samlp:Response>`));
  }

  // 25. An IdP error response (user cancelled / access denied), unsigned as
  //     most IdPs send it.
  write(
    'status-failure.xml',
    `<?xml version="1.0" encoding="UTF-8"?>
<samlp:Response xmlns:samlp="urn:oasis:names:tc:SAML:2.0:protocol" xmlns:saml="urn:oasis:names:tc:SAML:2.0:assertion" ID="${RESPONSE_ID}" Version="2.0" IssueInstant="${ISSUE_INSTANT}" Destination="${ACS_URL}" InResponseTo="${REQUEST_ID}">
  <saml:Issuer>${IDP_ENTITY_ID}</saml:Issuer>
  <samlp:Status>
    <samlp:StatusCode Value="urn:oasis:names:tc:SAML:2.0:status:Responder">
      <samlp:StatusCode Value="urn:oasis:names:tc:SAML:2.0:status:AuthnFailed"/>
    </samlp:StatusCode>
    <samlp:StatusMessage>Access denied</samlp:StatusMessage>
  </samlp:Status>
</samlp:Response>`
  );

  // 26. Both Response and Assertion signed — the strictest legitimate shape.
  write('both-signed.xml', sign(withIdp(responseXml()), { ...idp, target: 'Response' }));

  const files = fs.readdirSync(OUT).sort();
  // eslint-disable-next-line no-console
  console.log(`Wrote ${files.length} fixture files to ${OUT}`);
  for (const f of files) console.log(`  ${f}`);
}

main();
