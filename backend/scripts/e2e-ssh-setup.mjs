/**
 * e2e-ssh-setup.mjs — provision everything frontend/e2e/terminal.spec.js
 * needs: a throwaway user, a Keystore identity, three connectable SSH
 * servers and an approved access request for each.
 *
 *   ./scripts/e2e-ssh-targets.sh up          # the three containers first
 *   node backend/scripts/e2e-ssh-setup.mjs
 *   node backend/scripts/e2e-ssh-setup.mjs --teardown
 *
 * WHAT THE APP ACTUALLY NEEDS FOR A CONNECTABLE SSH SERVER
 *
 * Two modes exist (Server.authMode). `certificate` is the default and the
 * one the product is built around: the host must have been bootstrapped so
 * sshd trusts the org CA, and it then accepts the short-lived cert
 * accessRequestService.generateSshCredentials() signs. `credential` is the
 * sanctioned Keystore exception (docs/keystore-and-quick-connect.md) — a
 * stored identity, no bootstrap, no agent.
 *
 * These targets use `credential`, because that is what a throwaway Docker
 * container honestly is: a host nobody bootstrapped. Everything else follows
 * the app's own rules rather than being forced into the database —
 *
 *   - the key pair is generated by keystoreService.generateKey(), so the
 *     private half is AES-256-GCM encrypted at rest like any other Keystore
 *     key, and the generation is audited;
 *   - the identity is keystoreService.createCredential() with authType
 *     'key', which is what the Keystore screen produces;
 *   - the servers are serverService.createServer(), which is what the
 *     Servers screen produces, and which validates the auth mode + identity
 *     pairing itself;
 *   - `isServerOnboarded()` is true for credential-mode servers with no
 *     agent, so the workspace's Connect button is enabled — no fake
 *     provisionStatus or agent heartbeat is invented here.
 *
 * The only row written by hand is the APPROVED AccessRequest, exactly as
 * e2e-browser-setup.mjs does for RDP: the approval workflow is not what the
 * terminal suite is testing.
 *
 * SECRETS: the account password is 24 random bytes, regenerated every run,
 * written only to frontend/e2e/.auth.ssh.json (0600, gitignored) and never
 * printed. The SSH private key never leaves the database; only its public
 * half is written to data/e2e-ssh/authorized_keys for the containers.
 */

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { execFileSync } from 'child_process';
import bcrypt from 'bcryptjs';
import { fileURLToPath } from 'url';

import prisma from '../src/config/db.js';
import * as keystoreService from '../src/services/keystoreService.js';
import * as serverService from '../src/services/serverService.js';
import { UNSCOPED } from '../src/lib/scope.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..', '..');
const AUTH_FILE = path.join(REPO, 'frontend', 'e2e', '.auth.ssh.json');
const KEYS_DIR = path.join(REPO, 'data', 'e2e-ssh');

const EMAIL = 'e2e-ssh@shellius.test';
const KEY_NAME = 'E2E terminal targets';
const CRED_NAME = 'E2E terminal identity';
const SSH_USER = 'e2e';

// hostname → compose service. Distinct hostnames are load-bearing: the shell
// prompt on each box is `e2e@<hostname>:~$`, which is how a two-tab test
// proves a keystroke landed in the tab it was aimed at.
const TARGETS = [
  { hostname: 'ssh-alpha', container: 'shellius-ssh-alpha-1', displayName: 'E2E ssh-alpha' },
  { hostname: 'ssh-bravo', container: 'shellius-ssh-bravo-1', displayName: 'E2E ssh-bravo' },
  { hostname: 'ssh-charlie', container: 'shellius-ssh-charlie-1', displayName: 'E2E ssh-charlie' },
];

const TEARDOWN = process.argv.includes('--teardown');

function containerIp(name) {
  try {
    const out = execFileSync(
      'docker',
      ['inspect', '-f', '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}', name],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }
    ).trim();
    return out || null;
  } catch {
    return null;
  }
}

const org = await prisma.organization.findFirst({ where: { name: 'Shellius Local' }, select: { id: true } });
if (!org) {
  console.error('no "Shellius Local" organization — is this the dev database?');
  process.exit(1);
}

async function teardown() {
  const user = await prisma.user.findFirst({ where: { orgId: org.id, email: EMAIL } });
  if (user) {
    await prisma.accessRequest.deleteMany({ where: { requesterId: user.id } });
    await prisma.session.deleteMany({ where: { userId: user.id } });
    await prisma.user.delete({ where: { id: user.id } });
  }
  // Servers first: Credential deletion is Restrict-guarded through SshKey.
  await prisma.server.deleteMany({ where: { orgId: org.id, hostname: { in: TARGETS.map((t) => t.hostname) } } });
  await prisma.credential.deleteMany({ where: { orgId: org.id, ownerId: null, name: CRED_NAME } });
  await prisma.sshKey.deleteMany({ where: { orgId: org.id, ownerId: null, name: KEY_NAME } });
  await fs.promises.rm(AUTH_FILE, { force: true });
  await fs.promises.rm(path.join(KEYS_DIR, 'authorized_keys'), { force: true });
  console.log('removed the end-to-end SSH user, identity, key and servers');
  process.exit(0);
}

if (TEARDOWN) await teardown();

// ── The three containers have to be running; we need their addresses ──────
const addresses = TARGETS.map((t) => ({ ...t, ip: containerIp(t.container) }));
const missing = addresses.filter((t) => !t.ip);
if (missing.length) {
  console.error(
    `not running: ${missing.map((m) => m.container).join(', ')}\n` +
      'start the SSH targets first:  ./scripts/e2e-ssh-targets.sh up'
  );
  process.exit(1);
}

const customer = await prisma.customer.findFirst({ where: { orgId: org.id }, select: { id: true, name: true } });
if (!customer) {
  console.error('no customer in this org — servers belong to a customer');
  process.exit(1);
}

const role = await prisma.role.findFirst({ where: { orgId: org.id, baseRole: 'admin' }, select: { id: true } });

// ── User ──────────────────────────────────────────────────────────────────
const password = crypto.randomBytes(24).toString('base64url');
const passwordHash = await bcrypt.hash(password, 10);

const user = await prisma.user.upsert({
  where: { orgId_email: { orgId: org.id, email: EMAIL } },
  update: { passwordHash, status: 'active', roleId: role?.id ?? undefined },
  create: {
    orgId: org.id,
    email: EMAIL,
    name: 'End-to-end SSH',
    passwordHash,
    role: 'admin',
    roleId: role?.id ?? undefined,
    status: 'active',
  },
  select: { id: true, email: true },
});

// ── Keystore identity (generated key, encrypted at rest by the service) ───
// Recreated every run so the public half on the containers and the private
// half in the database can never drift apart.
const existingServers = await prisma.server.findMany({
  where: { orgId: org.id, hostname: { in: TARGETS.map((t) => t.hostname) } },
  select: { id: true },
});
if (existingServers.length) {
  // Detach before deleting the identity — Server.credentialId is SetNull, but
  // the identity is about to be replaced and a dangling reference would make
  // the server unconnectable in a way that looks like a product failure.
  await prisma.server.updateMany({
    where: { id: { in: existingServers.map((s) => s.id) } },
    data: { credentialId: null, authMode: 'certificate' },
  });
}
await prisma.credential.deleteMany({ where: { orgId: org.id, ownerId: null, name: CRED_NAME } });
await prisma.sshKey.deleteMany({ where: { orgId: org.id, ownerId: null, name: KEY_NAME } });

const { key } = await keystoreService.generateKey(
  org.id,
  { name: KEY_NAME, description: 'Throwaway key for the Playwright terminal suite', keyType: 'ed25519', comment: 'shellius-e2e' },
  user.id,
  { ownerId: null }
);

const { credential } = await keystoreService.createCredential(
  org.id,
  {
    name: CRED_NAME,
    description: 'Throwaway identity for the Playwright terminal suite',
    username: SSH_USER,
    authType: 'key',
    sshKeyId: key.id,
    tags: ['e2e'],
  },
  user.id,
  { ownerId: null }
);

// The public half goes to the containers. Written before any server row is
// touched so a connection can never be attempted against a box that has not
// been told about this key yet.
await fs.promises.mkdir(KEYS_DIR, { recursive: true });
await fs.promises.writeFile(path.join(KEYS_DIR, 'authorized_keys'), `${key.publicKey.trim()}\n`, { mode: 0o644 });

// ── Servers ───────────────────────────────────────────────────────────────
const servers = [];
for (const target of addresses) {
  const existing = await prisma.server.findFirst({
    where: { orgId: org.id, hostname: target.hostname },
    select: { id: true },
  });

  const data = {
    hostname: target.hostname,
    displayName: target.displayName,
    description: 'Throwaway Docker SSH target for the Playwright terminal suite',
    ipAddress: target.ip,
    port: 22,
    protocol: 'ssh',
    environment: 'dev',
    sshUser: SSH_USER,
    authMode: 'credential',
    credentialId: credential.id,
    isActive: true,
  };

  const server = existing
    ? await serverService.updateServer(org.id, existing.id, data, UNSCOPED)
    : await serverService.createServer(org.id, customer.id, data, UNSCOPED);

  // Host keys are generated when a container first boots, so recreating one
  // changes its fingerprint and Shellius (correctly) refuses to connect with
  // HOST_KEY_MISMATCH. Clearing the pin here is the equivalent of an admin
  // resetting it after a reinstall — which is exactly what happened.
  await prisma.server.update({
    where: { id: server.id },
    data: { hostKeyFingerprint: null, hostKeyAlgorithm: null, hostKeyPinnedAt: null },
  });

  servers.push({ id: server.id, hostname: target.hostname, displayName: target.displayName, ip: target.ip });
}

// ── One APPROVED, unexpired access request per server ─────────────────────
await prisma.accessRequest.deleteMany({ where: { requesterId: user.id } });
for (const server of servers) {
  const request = await prisma.accessRequest.create({
    data: {
      orgId: org.id,
      requesterId: user.id,
      serverId: server.id,
      status: 'APPROVED',
      protocol: 'SSH',
      reason: 'Automated browser verification of the terminal workspace',
      requestedPrincipal: SSH_USER,
      requestedDuration: 7200,
      approvedDuration: 7200,
      approvedAt: new Date(),
      expiresAt: new Date(Date.now() + 2 * 60 * 60 * 1000),
    },
    select: { id: true },
  });
  server.requestId = request.id;
}

await fs.promises.mkdir(path.dirname(AUTH_FILE), { recursive: true });
await fs.promises.writeFile(
  AUTH_FILE,
  JSON.stringify({ email: EMAIL, password, sshUser: SSH_USER, servers }, null, 2),
  { mode: 0o600 }
);

console.log('e2e user      :', user.email);
console.log('identity      :', credential.name, `(key ${key.fingerprint})`);
console.log('authorized_keys:', path.relative(REPO, path.join(KEYS_DIR, 'authorized_keys')));
for (const s of servers) console.log('server        :', s.hostname, s.ip, '→ approved request', s.requestId);
console.log('credentials   : frontend/e2e/.auth.ssh.json (0600, gitignored, password not shown)');
process.exit(0);
